import { mkdir, readdir, readFile, rm } from "node:fs/promises";
import path from "node:path";

import { normalizeRoute } from "./nav";
import { writeIfChanged } from "./write";

export const GENERATED_MARKER = "// @generated by construkt-kit-docs";

const ROUTER_PACKAGE = "@tanstack/react-router";

const toPosix = (value: string) => value.split(path.sep).join("/");

export interface RoutePage {
  route: string;
  /** Absolute path of the page's MDX file. */
  file: string;
  /** Absolute path of the route file the CLI writes for it. */
  routeFile: string;
}

const ROUTE_FILE = /\.[jt]sx?$/;

/**
 * The route file for a page, from its path under `contentDir` without `.mdx`: `projects` →
 * `<routesDir>/projects.tsx`, `guide/index` → `guide/index.tsx`, TanStack's index route for `guide/`.
 * Dots are escaped, so `v1.2` stays one segment.
 */
export const routeFileFor = (routesDir: string, page: string) =>
  path.join(routesDir, `${page.replaceAll(".", "[.]")}.tsx`);

const routeSegments = (routesRoot: string, routeFile: string) =>
  toPosix(path.relative(routesRoot, routeFile))
    .replace(ROUTE_FILE, "")
    .split("/")
    .flatMap((part) => part.match(/(?:\[[^\]]*\]|[^.])+/g) ?? []);

const unescape = (segment: string) => segment.replace(/\[([^\]]*)\]/g, "$1");

/** TanStack's id for a route file: its segments under the routes root, `index` as a trailing slash. */
export const routeIdOf = (routesRoot: string, routeFile: string) => {
  const segments = routeSegments(routesRoot, routeFile).map(unescape);
  if (segments.at(-1) === "index") segments[segments.length - 1] = "";
  return `/${segments.join("/")}`;
};

export const routeUrlOf = (routesRoot: string, routeFile: string) => {
  const segments = routeSegments(routesRoot, routeFile);
  if (segments.at(-1) === "lazy") segments.pop();

  const last = segments.at(-1);
  if (!last || last === "route" || last.startsWith("_")) return undefined;
  if (segments.some((segment) => segment.startsWith("-") || segment.includes("$")))
    return undefined;
  if (last === "index") segments.pop();

  const url = segments
    .filter((segment) => !/^\(.*\)$/.test(segment) && !segment.startsWith("_"))
    .map((segment) => unescape(segment.replace(/_$/, "")));
  return normalizeRoute(`/${url.join("/")}`);
};

const isGenerated = async (file: string) =>
  (await readFile(file, "utf8")).startsWith(GENERATED_MARKER);

const listRouteFiles = async (dir: string) => {
  try {
    const entries = await readdir(dir, { recursive: true, withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && ROUTE_FILE.test(entry.name))
      .map((entry) => path.join(entry.parentPath, entry.name));
  } catch {
    return [];
  }
};

export interface HandWrittenRoute {
  route: string;
  id: string;
  file: string;
}

/** The routes the site's own files under `routesDir` serve, so links to them resolve. */
export const handWrittenRoutes = async (routesRoot: string, routesDir: string) => {
  const routes: HandWrittenRoute[] = [];

  for (const file of await listRouteFiles(routesDir)) {
    const route = routeUrlOf(routesRoot, file);
    if (route !== undefined && !(await isGenerated(file)))
      routes.push({ route, id: routeIdOf(routesRoot, file), file });
  }

  return routes;
};

export const clashesWith = (route: HandWrittenRoute, routesRoot: string, routeFile: string) =>
  route.id.endsWith("/") || !routeIdOf(routesRoot, routeFile).startsWith(`${route.id}/`);

export interface WriteRoutesOptions {
  routesRoot: string;
  routesDirs: string[];
  headModule: string;
  pages: RoutePage[];
}

const routeSource = (page: RoutePage, routesRoot: string, headModule: string) => {
  const content = toPosix(path.relative(path.dirname(page.routeFile), page.file));
  const id = routeIdOf(routesRoot, page.routeFile);
  const route = normalizeRoute(page.route);

  return [
    GENERATED_MARKER,
    `import { createFileRoute } from ${JSON.stringify(ROUTER_PACKAGE)};`,
    ``,
    `import { pageHead } from ${JSON.stringify(headModule)};`,
    ``,
    `import Content from ${JSON.stringify(/^\.\.?\//.test(content) ? content : `./${content}`)};`,
    ``,
    `export const Route = createFileRoute(${JSON.stringify(id)})({`,
    `  head: () => pageHead(${JSON.stringify(route)}),`,
    `  component: Content,`,
    `});`,
    ``,
  ].join("\n");
};

/** Writes one route file per page and deletes generated ones whose page is gone. */
export const writeRouteFiles = async ({
  routesRoot,
  routesDirs,
  headModule,
  pages,
}: WriteRoutesOptions) => {
  const wanted = new Set(pages.map((page) => page.routeFile));

  for (const dir of routesDirs) {
    for (const file of await listRouteFiles(dir)) {
      if (!wanted.has(file) && (await isGenerated(file))) await rm(file);
    }
  }

  for (const page of pages) {
    await mkdir(path.dirname(page.routeFile), { recursive: true });
    await writeIfChanged(page.routeFile, routeSource(page, routesRoot, headModule));
  }
};
